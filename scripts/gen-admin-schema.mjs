// Generates src/lib/admin/schema.generated.ts from the Supabase types file:
// one entry per public table with its Row columns and a coarse type, so the
// admin data engine can list/edit any table without a hand-written config.
//
//   node scripts/gen-admin-schema.mjs
import ts from "typescript";
import { readFileSync, writeFileSync } from "node:fs";

const SRC = "src/integrations/supabase/types.ts";
const OUT = "src/lib/admin/schema.generated.ts";

const source = ts.createSourceFile(SRC, readFileSync(SRC, "utf8"), ts.ScriptTarget.Latest, true);

/** Coarse kind for the admin editor. */
function kindOf(typeText) {
  const t = typeText.replace(/\s*\|\s*null/g, "").trim();
  if (t === "string") return "text";
  if (t === "number") return "number";
  if (t === "boolean") return "boolean";
  if (t === "Json") return "json";
  if (t.startsWith("Database[\"public\"][\"Enums\"]")) return "enum";
  if (t.endsWith("[]")) return "array";
  return "text";
}

function enumName(typeText) {
  const m = /Enums"\]\["([a-z_]+)"\]/.exec(typeText);
  return m ? m[1] : null;
}

const tables = {};
let enums = {};

function visit(node) {
  // Database.public.Tables.<name>.Row
  if (ts.isPropertySignature(node) && node.name.getText() === "Tables" && node.type && ts.isTypeLiteralNode(node.type)) {
    for (const tbl of node.type.members) {
      if (!ts.isPropertySignature(tbl) || !tbl.type || !ts.isTypeLiteralNode(tbl.type)) continue;
      const tableName = tbl.name.getText().replace(/"/g, "");
      const row = tbl.type.members.find((m) => ts.isPropertySignature(m) && m.name.getText() === "Row");
      if (!row || !row.type || !ts.isTypeLiteralNode(row.type)) continue;
      const columns = [];
      for (const col of row.type.members) {
        if (!ts.isPropertySignature(col) || !col.type) continue;
        const typeText = col.type.getText();
        columns.push({
          name: col.name.getText().replace(/"/g, ""),
          kind: kindOf(typeText),
          nullable: /\|\s*null\b/.test(typeText),
          enum: enumName(typeText),
        });
      }
      tables[tableName] = columns;
    }
  }
  if (ts.isPropertySignature(node) && node.name.getText() === "Enums" && node.type && ts.isTypeLiteralNode(node.type)) {
    for (const en of node.type.members) {
      if (!ts.isPropertySignature(en) || !en.type) continue;
      const name = en.name.getText().replace(/"/g, "");
      const values = [];
      const collect = (t) => {
        if (ts.isUnionTypeNode(t)) t.types.forEach(collect);
        else if (ts.isLiteralTypeNode(t) && ts.isStringLiteral(t.literal)) values.push(t.literal.text);
      };
      collect(en.type);
      if (values.length) enums[name] = values;
    }
  }
  ts.forEachChild(node, visit);
}
visit(source);

const header = `// AUTO-GENERATED by scripts/gen-admin-schema.mjs from ${SRC}. Do not edit.
// Column catalogue for the admin data engine (one entry per public table).
export type ColumnKind = "text" | "number" | "boolean" | "json" | "enum" | "array";
export interface ColumnMeta { name: string; kind: ColumnKind; nullable: boolean; enum: string | null }
`;
const body =
  `export const TABLE_COLUMNS: Record<string, ColumnMeta[]> = ${JSON.stringify(tables, null, 1)} as const;\n\n` +
  `export const ENUM_VALUES: Record<string, string[]> = ${JSON.stringify(enums, null, 1)};\n`;
writeFileSync(OUT, header + body);
console.log(`wrote ${OUT}: ${Object.keys(tables).length} tables, ${Object.keys(enums).length} enums`);
